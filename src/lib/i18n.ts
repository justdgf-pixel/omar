export function t(locale: Locale, key: string): string {
  return dictionaries[locale][key] ?? dictionaries[DEFAULT_LOCALE][key] ?? key;
}

/** Picks a multilingual field from a record like `{ titleAr, titleFr, titleEn }`. */
export function pickI18nField(
  obj: Record<string, unknown>,
  base: string,
  locale: Locale,
): string {
  const suffix = locale === "ar" ? "Ar" : locale === "fr" ? "Fr" : "En";
  const v = obj[`${base}${suffix}`] as string | undefined;
  if (v) return v;
  return (
    (obj[`${base}Fr`] as string | undefined) ??
    (obj[`${base}En`] as string | undefined) ??
    (obj[`${base}Ar`] as string | undefined) ??
    ""
  );
}
